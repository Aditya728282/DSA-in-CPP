#include <iostream>
using namespace std;
int main(){
    // Increment Or Decriment  Operator
    int a=5;
    int b=6;
    //Pre Increment 
    cout<<(++a)<<endl; 
    cout<<(++b)<<endl;
    // Pre-Decrement 
    cout<<(--a)<<endl;
    cout<<(--b)<<endl;
    cout<<endl;

    // Post- Increment
    cout<<(a++)<<endl;
    cout<<(b++)<<endl;
    // Post-Decrement
    cout<<(a--)<<endl;
    cout<<(b--)<<endl;

return 0;

}